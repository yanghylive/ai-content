#!/usr/bin/env node

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const backendRoot = join(scriptDir, '..');
const sourcePath = join(backendRoot, 'prisma', 'schema.prisma');
const targetPath = join(backendRoot, 'prisma', 'schema.sqlite.prisma');
const binaryTargetsByPlatform = {
  'mac-arm64': ['darwin-arm64'],
  'mac-x64': ['darwin'],
  'win-x64': ['windows'],
  'linux-x64': ['debian-openssl-3.0.x'],
};

function resolveBinaryTargets() {
  const explicit = process.env.KAYPAL_PRISMA_BINARY_TARGETS;
  if (explicit) {
    return explicit.split(',').map((target) => target.trim()).filter(Boolean);
  }
  const buildPlatform = process.env.BUILD_PLATFORM;
  if (buildPlatform && binaryTargetsByPlatform[buildPlatform]) {
    return binaryTargetsByPlatform[buildPlatform];
  }
  return [];
}

let schema = readFileSync(sourcePath, 'utf8');
const binaryTargets = resolveBinaryTargets();

schema = schema
  .replace('provider = "postgresql"', 'provider = "sqlite"')
  .replace('url      = env("DATABASE_URL")', 'url      = env("SQLITE_DATABASE_URL")')
  .replaceAll(' @db.Text', '')
  .replaceAll(' @db.Date', '')
  // SQLite 不支持 Decimal / 任意 @db.NativeType → 去注解并将 Decimal 转 Float
  .replace(/ @db\.[A-Za-z0-9_]+(?:\([^)]*\))?/g, '')
  .replace(/\bDecimal\b/g, 'Float')
  .replace(
    /keywords\s+String\[\]\s+\/\/ PostgreSQL 数组类型/g,
    'keywords    Json      @default("[]")'
  )
  .replace(/keywords\s+String\[\]/g, 'keywords    Json      @default("[]")')
  .replace(
    /searchQueries\s+String\[\]\s+@map\("search_queries"\)\s+\/\/ AI 建议的搜索词组/g,
    'searchQueries Json      @default("[]") @map("search_queries")'
  )
  // 通用兜底：其余标量列表 String[]（如 ShowcaseCase.platforms/industries/capabilityTags/keyFeatures/deliveryModes、
  // allowedDevices 等）转 Json。SQLite 不支持标量列表；Prisma 对 Json 字段读写数组透明。
  .replace(/\b(\w+)\s+String\[\]/g, '$1 Json @default("[]")')
  .replace(
    /taskType\s+InteractionTaskType\s+@map\("taskType"\)/g,
    'taskType                   String                @map("taskType")'
  )
  .replace(
    /status\s+InteractionTaskStatus @default\(QUEUED\)/g,
    'status                     String                @default("QUEUED")'
  )
  .replace(
    /\n\/\/ 交互任务枚举（migration 20260530140948 \+ 20260601010300 加了 2 个值）\nenum InteractionTaskType \{[\s\S]*?\nenum AgentRiskLevel \{[\s\S]*?\n\}\n/g,
    '\n// SQLite product schema stores enum-like values as String for local portability.\n'
  );

if (binaryTargets.length > 0) {
  const binaryTargetsLine = `  binaryTargets = [${binaryTargets.map((target) => `"${target}"`).join(', ')}]`;
  if (/binaryTargets\s*=\s*\[[^\]]+\]/.test(schema)) {
    schema = schema.replace(/\s*binaryTargets\s*=\s*\[[^\]]+\]/, `\n${binaryTargetsLine}`);
  } else {
    schema = schema.replace(
      /(generator\s+client\s*\{[\s\S]*?provider\s*=\s*"prisma-client-js"[^\n]*\n)/,
      `$1${binaryTargetsLine}\n`
    );
  }
}

const header = `// Generated by backend/scripts/prepare-sqlite-schema.mjs.\n// Do not edit manually; edit prisma/schema.prisma and regenerate.\n\n`;

writeFileSync(targetPath, `${header}${schema}`, 'utf8');
console.log(`Generated ${targetPath}`);
